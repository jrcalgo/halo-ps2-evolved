def _lines(path):
    return Path(path).read_text(encoding="latin-1").split("\n")


def _function_verbatim(path, signature, after_line=0):
    """Verbatim text from a definition line starting with `signature` through the
    first following line that is exactly `}` or `};`."""
    lines = _lines(path)
    for index, line in enumerate(lines):
        if index < after_line:
            continue
        if line.startswith(signature) and not line.rstrip().endswith(";"):
            for end in range(index, len(lines)):
                if lines[end] in ("}", "};"):
                    return "\n".join(lines[index:end + 1]) + "\n"
            break
    raise AssertionError(f"signature not found in {path}: {signature}")


def _fragment_verbatim(path, start_text, close_after=None):
    """Verbatim lines from the unique line containing `start_text` through the
    first following line equal to that line's indentation followed by `}`.
    With `close_after`, the search for the closing brace starts after the first
    line containing that text (used for `for` loops whose body starts later)."""
    lines = _lines(path)
    starts = [i for i, line in enumerate(lines) if line.lstrip("\t ").startswith(start_text)]
    if len(starts) != 1:
        raise AssertionError(f"{start_text!r} occurs {len(starts)} times in {path}")
    start = starts[0]
    search = start
    if close_after is not None:
        marks = [i for i in range(start, len(lines)) if lines[i].lstrip("\t ").startswith(close_after)]
        if not marks:
            raise AssertionError(f"{close_after!r} not found after {start_text!r}")
        search = marks[0]
    indent = lines[start][: len(lines[start]) - len(lines[start].lstrip("\t "))]
    for end in range(search, len(lines)):
        if lines[end] == indent + "}" and end > start:
            return "\n".join(lines[start:end + 1]) + "\n"
    raise AssertionError(f"no closing brace for {start_text!r} in {path}")


