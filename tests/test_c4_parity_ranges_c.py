def _compile(main_source, executable, extra_include=None):
    compiler = shutil.which("gcc")
    if not compiler:
        raise unittest.SkipTest("GCC unavailable for C4 ranges-c probe")
    command = [
        compiler, *host_abi32_flags(), "-std=gnu99", "-O2", "-fshort-wchar",
        "-DHALO_PS2=1", "-D_X86_=1", "-D_STDCALL_SUPPORTED=1",
        "-D__cdecl=", "-D__stdcall=", "-D__fastcall=", "-D__declspec(x)=",
        "-D__COLLISION_USAGE_H=1", "-ffunction-sections", "-fdata-sections",
        "-Wno-unused-function", "-w",
        "-I" + str(HCU / "port/ps2/include"),
        "-I" + str(HCU / "port/include/xdk"),
        "-I" + str(HCU / "source/tag_files"),
        "-I" + str(HCU / "source/memory"),
        "-I" + str(HCU / "source/math"),
        "-I" + str(HCU / "source"), "-I" + str(HCU / "source/cseries"),
        "-I" + str(HCU / "source/objects"), "-I" + str(HCU / "source/scenario"),
        "-I" + str(HCU / "source/physics"), "-I" + str(HCU / "source/render"),
        "-I" + str(ROOT / "src"),
    ]
    if extra_include:
        command += ["-I" + str(extra_include)]
    command += [
        "-include", str(PREAMBLE), "-include", str(ORDER), "-include", str(HALO_LIMITS),
        str(main_source), "-Wl,--gc-sections", "-lm", "-o", str(executable),
    ]
    built = subprocess.run(command, capture_output=True, text=True)
    if built.returncode != 0:
        raise AssertionError((built.stdout + built.stderr)[-20000:])
    return executable


_CACHE = {}


def _probe(kind, *args):
    """Run one probe mode; returns its stdout (one result line)."""
    if kind not in _CACHE:
        OUT_DIR.mkdir(parents=True, exist_ok=True)
        if kind == "collision":
            _CACHE[kind] = _compile(COLLISION_MAIN, OUT_DIR / "c4-ranges-c-collision")
        else:
            _generate_inc(OUT_DIR)
            _CACHE[kind] = _compile(SPLICE_MAIN, OUT_DIR / "c4-ranges-c-splice", OUT_DIR)
    run = subprocess.run([str(_CACHE[kind]), *args], capture_output=True, text=True)
    if run.returncode in (-31, 159):
        raise unittest.SkipTest("sandbox blocks native ILP32 execution with SIGSYS")
    if run.returncode != 0:
        raise AssertionError(run.stdout + run.stderr)
    return run.stdout.strip()


def _kv(line):
    return dict(part.split("=", 1) for part in line.split() if "=" in part)


def _f32(value):
    import struct
    return struct.unpack("f", struct.pack("f", value))[0]


# ---------------------------------------------------------------- oracles

def _bit(bits, index):
    return (bits >> index) & 1 if index < 32 else 0


def _square_area_oracle(plane_normal_k, designator):
    """collision_surface_area: the CCW unit square doubles to 2 in xy; the plane
    designator picks plane 0 (normal k as given) or plane 1 (k=-1), and its sign
    bit negates the normal. The result is the positive part of 2*k."""
    plane_index = designator & LONG_MAX
    k = plane_normal_k if plane_index == 0 else -1.0
    if designator < 0:
        k = -k
    return max(0.0, 2.0 * k)


def _project_oracle(plane, projection, sign, px, py):
    """collision_surface_project_point2d via project_point2d (real_math.h)."""
    mapping = {(2, 1): (0, 1), (2, 0): (1, 0)}[(projection, 1 if sign else 0)]
    x, y = mapping
    n = plane["n"]
    out = [0.0, 0.0, 0.0]
    out[x] = px
    out[y] = py
    out[projection] = (plane["d"] - px * n[x] - py * n[y]) / n[projection]
    return out


def _leaf_oracle(args):
    """collision_leaf_test_vector + collision_bsp_valid_leaf for the leaf fixture."""
    refs_count = args["refs"]
    first = args["first"]
    leaf_count = refs_count
    nrefs = 2
    valid = leaf_count == 0 or (first >= 0 and leaf_count > 0 and first <= nrefs - leaf_count)
    if not valid:
        return None, 0
    references = [(args["designator"], args["root"]), (0, LONG_MIN)]
    surface = NONE
    for index in range(first, first + refs_count):
        designator, root = references[index]
        if (designator & LONG_MAX) != 0:
            continue
        sign_bit = designator < 0
        proj_sign = (True != sign_bit)
        hx, hy = args["hx"], args["hy"]
        p2d = (hx, hy) if proj_sign else (hy, hx)
        found = bsp2d_oracle(args, root, p2d)
        if 0 <= found < 2:
            surface = found
            break
    return surface, 1


def bsp2d_oracle(args, root, p2d):
    node_index = root
    if node_index == NONE:
        return NONE
    while not node_index < 0:
        if node_index >= 1:
            return NONE
        d = args["nx"] * p2d[0] + args["ny"] * p2d[1] - args["nd"]
        node_index = args["c"][0 if d < 0 else 1]
    if node_index == NONE:
        return NONE
    return node_index & LONG_MAX


def _bsp3d_oracle(args):
    point = (args["px"], args["py"], args["pz"])
    d = point[0] * args["ni"] + point[1] * args["nj"] + point[2] * args["nk"] - args["d"]
    node_index = args["c"][0 if d < 0 else 1]
    if node_index == NONE:
        return NONE
    if node_index < 0:
        return node_index & LONG_MAX
    return NONE  # out-of-range node index in this fixture (node count 1)


def _subcluster_oracle(indices, surfaces_count):
    flags = set()
    for index in indices:
        if index < 0 or index >= surfaces_count:
            continue
        flags.add(index)
    return sorted(flags)


def _cluster_oracle(values, lightmap_materials, vertex_bytes, surfaces_vertices, surfaces_count):
    """Independent restatement of structure_visibility.c traverse_surface_lists
    (group header [lightmap, material, n] then n surface indices), with the
    frustum treated as visible."""
    flags = set()
    consumed = 0
    pos = 0
    count = len(values)
    while consumed < count:
        if consumed > count - 3 or values[pos] < 0 or values[pos] >= len(lightmap_materials):
            break
        lightmap = values[pos]
        material = values[pos + 1]
        if material < 0 or material >= lightmap_materials[lightmap]:
            break
        vertex_limit = vertex_bytes[lightmap][material] // 0x20
        group_end = consumed + values[pos + 2] + 3
        consumed += 3
        pos += 3
        if group_end > count:
            group_end = count
        while consumed < group_end:
            surface = values[pos]
            pos += 1
            if surface < 0 or surface >= surfaces_count:
                consumed += 1
                continue
            if surface not in flags:
                verts = surfaces_vertices[surface]
                if all(v < vertex_limit for v in verts):
                    flags.add(surface)
            consumed += 1
    return sorted(flags)


def _weather_oracle(planes, position):
    inside = all(
        (n[0] * position[0] + n[1] * position[1] + n[2] * position[2] - d) >= 0.0
        for n, d in planes)
    return 0 if inside else 1


