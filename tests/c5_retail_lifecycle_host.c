/* The map's tag region is read at the Xbox tag base, where its pointers point (halo2ps2
 * tagindex.XBOX_TAG_BASE). CE's tag_get and the tag structures then run on the retail bytes
 * unchanged. Returns the tag count, or -1 with a message on stderr. */
#define C5_XBOX_TAG_BASE 0x803A6000u
void c5_cache_tags_attach(void *tag_header_address, long tag_count);

long c5_map_load(const char *path)
{
	unsigned char header[0x20];
	unsigned long tag_data_offset;
	unsigned long tag_data_size;
	unsigned char *region;
	int fd;
	long count;

	fd = open(path, O_RDONLY);
	if (fd < 0 || pread(fd, header, sizeof header, 0) != (ssize_t)sizeof header)
	{
		fprintf(stderr, "C5 error: cannot read map header %s\n", path);
		return -1;
	}
	tag_data_offset = header[0x10] | (header[0x11] << 8) | (header[0x12] << 16) | ((unsigned long)header[0x13] << 24);
	tag_data_size = header[0x14] | (header[0x15] << 8) | (header[0x16] << 16) | ((unsigned long)header[0x17] << 24);
	region = mmap((void *)C5_XBOX_TAG_BASE, tag_data_size, PROT_READ | PROT_WRITE,
		MAP_PRIVATE | MAP_ANONYMOUS | MAP_FIXED_NOREPLACE, -1, 0);
	if (region == MAP_FAILED || (unsigned long)region != C5_XBOX_TAG_BASE)
	{
		fprintf(stderr, "C5 error: cannot map the tag region at %08x\n", C5_XBOX_TAG_BASE);
		return -1;
	}
	if (pread(fd, region, tag_data_size, (off_t)tag_data_offset) != (ssize_t)tag_data_size)
	{
		fprintf(stderr, "C5 error: short read of the tag region\n");
		return -1;
	}
	close(fd);
	count = *(long *)(region + 0xC);
	c5_cache_tags_attach(region, count);
	return count;
}

