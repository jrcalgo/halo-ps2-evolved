char *csprintf(char *buffer, char *format, ...)
{
	va_list args;

	va_start(args, format);
	vsprintf(buffer, format, args);
	va_end(args);

	return buffer;
}

void error(short level, const char *format, ...)
{
	va_list args;

	(void)level;
	fprintf(stderr, "C5 error: ");
	va_start(args, format);
	vfprintf(stderr, format, args);
	va_end(args);
	fprintf(stderr, "\n");
}

/* CE's own assertion report (cseries.c display_assert): a failed match_assert in the closure is
 * the run's result, printed where the failing expression is, and the run ends (system_exit). */
void display_assert(char *expression, char *file, long line, boolean fatal)
{
	(void)fatal;
	fprintf(stdout, "C5 assert file=%s line=%ld expr=%s\n", file, line, expression ? expression : "");
	fflush(stdout);
}

void system_exit(long code)
{
	fprintf(stdout, "C5 exit system_exit=%ld\n", code);
	fflush(stdout);
	exit(3);
}
