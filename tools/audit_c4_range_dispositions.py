# --------------------------------------------------------------------------
# Specification.  Every claim below is re-verified against CE source by
# verify_row(); lines are never hard-coded (cites are resolved by needle).
# --------------------------------------------------------------------------
def M(name, sub, recv=None, scope=(), pat=None, children=(), decl=None, note=""):
    """A live CE member.  pat may contain {n}; recv is a receiver regex."""
    if pat is None:
        pat = (rf"\b(?:{recv})(?:\.|->){{n}}\b" if recv else r"(?:\.|->){n}\b")
    return dict(name=name, sub=sub, pat=pat, scope=list(scope), children=list(children), decl=decl, note=note)


def C(name, off, size, sub, pat=None, scope=(), note="", via=""):
    return dict(name=name, off=off, size=size, sub=sub, pat=pat, scope=list(scope), note=note, via=via)


def row(disposition, needs_fixture, consumer, why, cites, members, notes="", schema_addition=None,
        assert_no_refs=(), assert_refs=(), type_level=False):
    return dict(disposition=disposition, needs_fixture=needs_fixture, consumer=consumer, why=why,
                cites=list(cites), members=list(members), notes=notes, schema_addition=schema_addition,
                assert_no_refs=list(assert_no_refs), assert_refs=list(assert_refs), type_level=type_level)


