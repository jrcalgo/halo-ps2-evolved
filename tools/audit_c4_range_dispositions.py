def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def load(rel: str):
    return json.loads((ROOT / rel).read_text())


class Tree:
    """CE source/port files cached as line lists."""

    def __init__(self):
        self.files: dict[str, list[str]] = {}
        base = CE
        for sub in ("source", "port"):
            for path in sorted((base / sub).rglob("*")):
                if path.suffix not in (".c", ".h") or "third_party" in path.parts:
                    continue
                rel = path.relative_to(base).as_posix()
                try:
                    self.files[rel] = path.read_text(errors="replace").splitlines()
                except OSError:
                    continue
        self._funcs: dict[str, list[tuple[int, str]]] = {}

    def function_at(self, rel: str, line: int) -> str:
        if rel not in self._funcs:
            found = []
            for i, text in enumerate(self.files[rel], 1):
                if not text or text[0] in " \t#/*{}" or text.endswith(";") or "=" in text or text.startswith(
                        ("typedef", "struct", "union", "enum", "extern")):
                    continue
                m = re.match(r"^(?:static\s+)?[A-Za-z_][\w\s\*]*?\b([A-Za-z_]\w*)\s*\([^;]*$", text)
                if m:
                    found.append((i, m.group(1)))
            self._funcs[rel] = found
        name = ""
        for i, fn in self._funcs[rel]:
            if i <= line:
                name = fn
            else:
                break
        return name


TOOL_FUNCS = {"build_structure_lens_flares"}


def category(rel: str, func: str) -> str:
    base = rel.rsplit("/", 1)[-1]
    if rel.startswith("port/linux/game/tag_schema") or "tag_validate" in rel or "custom_edition" in rel:
        return "validator-load"
    if rel == "source/structures/leaf_map.c" or rel == "source/main/ps2_m2_ui_lifecycle_test.c":
        return "tool-debug-test"
    if "debug" in base or "debug" in func or func in TOOL_FUNCS:
        return "tool-debug-test"
    return "runtime"


WRITE = r"(?:\[[^\]]*\])*\s*(?:=(?!=)|\+=|-=|\*=|/=|\|=|&=|\^=|<<=|>>=|\+\+|--)"


def scan(tree: Tree, pat: str, scope: list[str], name: str) -> dict:
    rx = re.compile(pat.replace("{n}", re.escape(name)))
    wr = re.compile(WRITE)
    out = {"runtime-read": [], "tool-debug-test-read": [], "validator-load-read": [],
           "runtime-write": [], "tool-debug-test-write": [], "validator-load-write": []}
    for rel, lines in tree.files.items():
        if scope and not any(s in rel for s in scope):
            continue
        for i, text in enumerate(lines, 1):
            if text.lstrip().startswith(("/*", "*", "//")):
                continue
            matches = list(rx.finditer(text))
            if not matches:
                continue
            func = tree.function_at(rel, i)
            cat = category(rel, func)
            # a site is a write only if every matched access is directly followed by an assignment operator
            kinds = {"write" if wr.match(text[m.end():]) else "read" for m in matches}
            kind = "read" if "read" in kinds else "write"
            out[f"{cat}-{kind}"].append(f"{rel}:{i} ({func or '?'})")
    return out


def resolve_cite(tree: Tree, path: str, needle: str, nth: int = 1) -> int:
    rel = path.replace("submodules/halo-ce-universal/", "")
    lines = tree.files.get(rel)
    if lines is None:
        lines = (ROOT / path).read_text(errors="replace").splitlines()
    hits = [i for i, text in enumerate(lines, 1) if needle in text]
    if not hits:
        raise KeyError(f"cite not found: {path}: {needle!r}")
    return hits[nth - 1]


def find_decl(tree: Tree, path: str, start_line: int | None, struct_text: str | None, member: str) -> tuple[str, int, str] | None:
    rel = path.replace("submodules/halo-ce-universal/", "")
    lines = tree.files.get(rel)
    if lines is None:
        return None
    if start_line is None:
        hits = [i for i, text in enumerate(lines, 1) if text.startswith(struct_text)]
        if not hits:
            return None
        start_line = hits[0]
    rx = re.compile(rf"\b{re.escape(member)}\b")
    for i in range(start_line, min(len(lines), start_line + 80) + 1):
        text = lines[i - 1]
        if i > start_line and text.startswith("}"):
            break
        if rx.search(text) and i != start_line or (i == start_line and rx.search(text) and ";" in text):
            return f"submodules/halo-ce-universal/{rel}", i, text.strip()
    return None


def ledger_rows() -> dict:
    ledger = load(LEDGER)
    return OrderedDict((r["member"], r) for r in ledger["rows"])


def owner_occupancy(inventory: dict, census: dict, definition: str) -> list[dict]:
    paths = {f["path"]: f for f in census["fields"]}
    out = []
    for m in inventory["members"]:
        if m.get("child_definition_name") == definition and m["path"] in paths:
            f = paths[m["path"]]
            out.append({"owner_block": m["path"], "retail_nonempty_bsp_count": f["retail_nonempty_bsp_count"],
                        "retail_empty_bsp_count": f["retail_empty_bsp_count"]})
    return out


def layout_members(definition: str, key: str, range_layout: dict, eight: dict) -> tuple[list[dict], dict | None]:
    """Compiler/derived member offsets for a range: (members, source_declaration)."""
    for r in range_layout["ranges"]:
        if r["inventory_path"] == key and r.get("candidate_c_members"):
            return [dict(name=m["name"], offset=m["offset"], size=m["size"]) for m in r["candidate_c_members"]], r.get("source_declaration")
    for r in eight["ranges"]:
        if r["inventory_path"] == key:
            members = [dict(name=m["name"], offset=m["offset"], size=m["size"]) for m in r["members"]]
            return members, None
    return [], None


def verify_row(key: str, spec: dict, ledger_row: dict, tree: Tree, inventory, census, range_layout, eight) -> tuple[dict, list[str]]:
    errors: list[str] = []
    definition = ledger_row["definition"]
    lay, src_decl = layout_members(definition, key, range_layout, eight)
    lay_by_name = {m["name"]: m for m in lay}
    members_out = []
    for m in spec["members"]:
        entry = {"name": m["name"], "disposition": m["sub"]}
        # offsets/sizes from layout (hierarchy children carry explicit offsets)
        if m["name"] in lay_by_name:
            entry["offset"] = lay_by_name[m["name"]]["offset"]
            entry["size"] = lay_by_name[m["name"]]["size"]
        elif m["name"] == "x" and definition == "real_point2d":
            entry["offset"], entry["size"] = 0, 4
        elif m["name"] == "y" and definition == "real_point2d":
            entry["offset"], entry["size"] = 4, 4
        elif m["name"] in ("n", "d", "z") or definition in ("byte", "long", "detail_object_count", "structure_node"):
            entry["offset"], entry["size"] = None, None
        else:
            # members listed in the layout under a different spelling are an error
            entry["offset"], entry["size"] = None, None
            if lay and m["name"] not in lay_by_name and not m["children"]:
                errors.append(f"{key}: member {m['name']} is not in the compiler layout {sorted(lay_by_name)}")
        # declaration
        decl = None
        if m["decl"]:
            decl = find_decl(tree, m["decl"][0], None, m["decl"][1], m["name"]) if m["name"] != "value" else None
            if m["name"] == "value":
                line = resolve_cite(tree, m["decl"][0], m["decl"][1])
                decl = (m["decl"][0], line, m["decl"][1])
        elif src_decl:
            decl = find_decl(tree, src_decl["path"], src_decl["line"], None, m["name"])
        if decl is None and not m["children"] and definition not in ("byte", "long"):
            if m["name"] not in ("n", "d", "z", "x", "y", "surface_indices", "pathfinding_surfaces",
                                 "pathfinding_edges", "portal_designators"):
                errors.append(f"{key}: no declaration found for member {m['name']}")
        if decl:
            entry["declaration"] = f"{decl[0]}:{decl[1]}: {decl[2]}"
        # live members declared as part of owner types for type-level rows
        if m["name"] in ("surface_indices", "pathfinding_surfaces", "pathfinding_edges", "portal_designators"):
            owner = {"surface_indices": "structure_cluster/structure_subcluster", "pathfinding_surfaces": "structure_bsp",
                     "pathfinding_edges": "structure_bsp", "portal_designators": "map_leaf"}[m["name"]]
            entry["owner_member_of"] = owner
        if m["note"]:
            entry["note"] = m["note"]
        children = []
        subs = [m] if not m["children"] else []
        if m["children"]:
            for c in m["children"]:
                acc = scan(tree, c["pat"], c["scope"] or [], c["name"]) if c["pat"] else {}
                child = {"name": f"{m['name']}.{c['name']}", "offset": lay_by_name.get(m["name"], {}).get("offset", 0) + c["off"],
                         "size": c["size"], "disposition": c["sub"]}
                d = find_decl(tree, "submodules/halo-ce-universal/source/rasterizer/rasterizer_geometry.h", None,
                              "struct vertex_buffer", c["name"])
                if d:
                    child["declaration"] = f"{d[0]}:{d[1]}: {d[2]}"
                else:
                    errors.append(f"{key}: no declaration for {child['name']}")
                child.update(access_summary(acc))
                if c.get("via"):
                    child["via"] = c["via"]
                errors += check_sub(key, child["name"], c["sub"], acc, spec, bool(c.get("via")))
                children.append(child)
            entry["children"] = children
        else:
            acc = scan(tree, m["pat"], m["scope"], m["name"])
            entry.update(access_summary(acc))
            errors += check_sub(key, m["name"], m["sub"], acc, spec)
        members_out.append(entry)

    # reference assertions
    for rx, allowed in spec["assert_no_refs"]:
        compiled = re.compile(rx)
        for rel, lines in tree.files.items():
            if any(rel.endswith(a) for a in allowed):
                continue
            for i, text in enumerate(lines, 1):
                if compiled.search(text):
                    errors.append(f"{key}: unexpected reference {rel}:{i}: {text.strip()[:80]}")

    # citations
    cites = []
    for path, needle in spec["cites"]:
        try:
            cites.append({"path": path, "line": resolve_cite(tree, path, needle), "needle": needle})
        except KeyError as exc:
            errors.append(f"{key}: {exc}")

    # row disposition = strongest member disposition
    rolled = max((c["disposition"] for m in members_out for c in ([m] if "children" not in m else m["children"])),
                 key=lambda d: RANK[d])
    if rolled != spec["disposition"]:
        errors.append(f"{key}: declared row disposition {spec['disposition']} != rolled-up member disposition {rolled}")
    if spec["disposition"] == "blocked" and not spec.get("notes"):
        errors.append(f"{key}: blocked without a reason")
    if spec["disposition"] == "schema-gap" and not spec["schema_addition"]:
        errors.append(f"{key}: schema-gap without a stated schema addition")
    if spec["disposition"] in ("consumed", "schema-gap") and not spec["needs_fixture"]:
        errors.append(f"{key}: {spec['disposition']} must list needs_fixture")
    if spec["disposition"] in ("preserved-opaque", "runtime-normalized") and spec["needs_fixture"]:
        errors.append(f"{key}: {spec['disposition']} must not list needs_fixture")

    evidence = spec["why"] + " Cites: " + "; ".join(f"{c['path']}:{c['line']}" for c in cites) + "."
    out = OrderedDict()
    out["ledger_member"] = key
    out["disposition"] = spec["disposition"]
    out["evidence"] = evidence
    out["live_members"] = members_out
    out["needs_fixture"] = bool(spec["needs_fixture"])
    out["notes"] = spec["notes"]
    out["struct"] = definition
    out["offset"] = ledger_row["offset"]
    out["size"] = ledger_row["size"]
    out["ledger_family"] = ledger_row["family"]
    out["consumer"] = spec["consumer"]
    out["citations"] = cites
    out["owner_block_retail_occupancy"] = owner_occupancy(inventory, census, definition)
    out["type_level"] = spec["type_level"]
    if spec["schema_addition"]:
        out["schema_addition"] = spec["schema_addition"]
    return out, errors


def access_summary(acc: dict) -> dict:
    def trim(lst):
        return sorted(lst)[:8]
    return OrderedDict([
        ("reads_runtime_count", len(acc.get("runtime-read", []))),
        ("reads_runtime_sites", trim(acc.get("runtime-read", []))),
        ("reads_debug_tool_test_count", len(acc.get("tool-debug-test-read", []))),
        ("reads_validator_load_count", len(acc.get("validator-load-read", []))),
        ("writes_validator_load_count", len(acc.get("validator-load-write", []))),
        ("writes_validator_load_sites", trim(acc.get("validator-load-write", []))),
        ("writes_tool_debug_test_count", len(acc.get("tool-debug-test-write", []))),
        ("writes_runtime_count", len(acc.get("runtime-write", []))),
        ("writes_runtime_sites", trim(acc.get("runtime-write", []))),
    ])


GENERIC_NAMES = {"pad", "pad1", "unused", "flags", "name", "x", "y", "plane_index", "leaf_indices", "node_index",
                 "portal_designators", "pathfinding_edges", "offset", "point_light_indices"}
_GLOBAL_TREE: list = []


def global_name_hits(name: str) -> list[str]:
    """Any access `.name` / `->name` in the whole CE tree (declarations have none)."""
    tree = _GLOBAL_TREE[0]
    acc = scan(tree, r"(?:\.|->){n}\b", [], name)
    return [site for k, v in acc.items() for site in v]


def check_sub(key: str, name: str, sub: str, acc: dict, spec: dict, via: bool = False) -> list[str]:
    errs = []
    base = name.split(".")[-1]
    if sub == "preserved-opaque" and base not in GENERIC_NAMES:
        hits = global_name_hits(base)
        if hits:
            errs.append(f"{key}: preserved-opaque member {name} has accesses somewhere in CE source: {hits[:3]}")
    if spec["type_level"] and sub == "consumed":
        # type-level members are evidenced by owner-block cites; require at least one hit anywhere (read counts)
        if not (acc.get("runtime-read") or acc.get("validator-load-read")):
            errs.append(f"{key}: type-level member {name} has no access sites")
        return errs
    if sub == "consumed" and via and (acc.get("runtime-read") or acc.get("validator-load-read")):
        return errs
    if sub == "consumed" and not acc.get("runtime-read"):
        errs.append(f"{key}: member {name} declared consumed but has no runtime read")
    if sub == "preserved-opaque":
        if acc.get("runtime-read") or acc.get("runtime-write"):
            errs.append(f"{key}: member {name} declared preserved-opaque but has runtime accesses "
                        f"{(acc.get('runtime-read') or []) + (acc.get('runtime-write') or [])}")
    if sub == "runtime-normalized" and not acc.get("validator-load-write"):
        errs.append(f"{key}: member {name} declared runtime-normalized without a load/validator write")
    if sub == "schema-gap":
        if acc.get("runtime-write"):
            errs.append(f"{key}: schema-gap member {name} has runtime writes")
    return errs


def build() -> tuple[dict, list[str]]:
    errors: list[str] = []
    ledger = ledger_rows()
    inventory = load(INVENTORY)
    census = load(EMPTY_CENSUS)
    range_layout = load(RANGE_LAYOUT)
    eight = load(EIGHT_LAYOUT)
    tree = Tree()
    _GLOBAL_TREE.clear()
    _GLOBAL_TREE.append(tree)

    # coverage: every range row the ledger flagged (or already ingested) must have a disposition
    targets = [m for m, r in ledger.items() if r["inventory_classification"] == "unclassified"
               and (r.get("gap_type") == "unclassified-dwarf-range" or r.get("range_source"))]
    for m in targets:
        if m not in SPEC:
            errors.append(f"unresolved range: {m} has no disposition")
    for m in SPEC:
        if m not in ledger:
            errors.append(f"spec row {m} is not a ledger member")
        elif ledger[m]["inventory_classification"] != "unclassified":
            errors.append(f"spec row {m} is not an unclassified DWARF range in the ledger")

    rows = []
    for m in ledger:
        if m not in SPEC:
            continue
        row_out, errs = verify_row(m, SPEC[m], ledger[m], tree, inventory, census, range_layout, eight)
        rows.append(row_out)
        errors += errs
    counts = {d: sum(1 for r in rows if r["disposition"] == d) for d in DISPOSITIONS}
    fixtures = [r["ledger_member"] for r in rows if r["needs_fixture"]]
    inputs = {rel: sha256(ROOT / rel) for rel in (RANGE_LAYOUT, EIGHT_LAYOUT, EIGHT_SOURCE_MAP, INVENTORY, EMPTY_CENSUS)}
    cited = sorted({c["path"] for r in rows for c in r["citations"]})
    payload = OrderedDict()
    payload["format"] = FORMAT
    payload["lane"] = "ranges"
    payload["generated_by"] = "tools/audit_c4_range_dispositions.py"
    payload["inputs"] = inputs
    payload["cited_source_sha256"] = {p: sha256(ROOT / p) for p in cited}
    payload["summary"] = {"range_rows": len(rows), "counts": counts, "needs_fixture_count": len(fixtures),
                          "unresolved": sum(1 for m in targets if m not in SPEC)}
    payload["needs_fixture"] = fixtures
    payload["rows"] = rows
    return payload, errors


def write_markdown(payload: dict) -> str:
    s = payload["summary"]
    lines = ["# M4 C4 DWARF-range dispositions (2026-10-26)", "",
             "Generated by `tools/audit_c4_range_dispositions.py --write`. Machine-readable rows: "
             "[`m4-c4-range-dispositions-2026-10-26.json`](m4-c4-range-dispositions-2026-10-26.json), ingested by "
             "`tools/audit_c4_member_ledger.py`.", "",
             "Each of the 43 ledger rows with gap type `unclassified-dwarf-range` is resolved below. Declaration lines, access "
             "sites and citations are regenerated from CE source on every run; a declared member disposition that the "
             "regenerated accesses contradict fails the checker. Bytes of every range stay protected by the exact-range "
             "preservation check (`docs/reports/retail-bsp-preservation-2026-10-21.json`); dispositions describe meaning, "
             "not retention.", "",
             "## Counts", "", "| disposition | rows |", "| --- | ---: |"]
    for d in DISPOSITIONS:
        lines.append(f"| {d} | {s['counts'][d]} |")
    lines += ["", f"Rows needing a member-exact parity fixture: {s['needs_fixture_count']}.", "",
              "Row disposition is the strongest member disposition (preserved-opaque < runtime-normalized < consumed < "
              "schema-gap < blocked). No row is runtime-normalized: no persisted range member is reset or filled at load "
              "(the validator only corrects out-of-domain values), and the walk journal's normalizations are all pointer/"
              "definition slots outside these ranges. `runtime_`-prefixed weather fields have no accesses, so they are "
              "preserved-opaque on zero-access evidence.", "",
              "## Needs member-exact fixture", ""]
    for m in payload["needs_fixture"]:
        lines.append(f"- `{m}`")
    lines += ["", "## Rows", ""]
    for r in payload["rows"]:
        lines += [f"### `{r['ledger_member']}`", "",
                  f"- struct `{r['struct']}` offset {r['offset']} size {r['size']}; family {r['ledger_family']}; "
                  f"**{r['disposition']}**; needs fixture: {'yes' if r['needs_fixture'] else 'no'}",
                  f"- consumer: {r['consumer']}", f"- evidence: {r['evidence']}"]
        if r["owner_block_retail_occupancy"]:
            occ = ", ".join(f"{o['owner_block']} {o['retail_nonempty_bsp_count']}/{o['retail_nonempty_bsp_count'] + o['retail_empty_bsp_count']}"
                            for o in r["owner_block_retail_occupancy"])
            lines.append(f"- retail non-empty BSPs by owner block: {occ}")
        if r.get("schema_addition"):
            lines.append(f"- schema addition: {r['schema_addition']}")
        if r["notes"]:
            lines.append(f"- notes: {r['notes']}")
        lines += ["", "| live member | off | size | declaration | disposition | MP reads | validator/load writes | runtime writes |",
                  "| --- | ---: | ---: | --- | --- | ---: | ---: | ---: |"]

        def emit(m):
            decl = m.get("declaration", "").replace("submodules/halo-ce-universal/", "")
            if "children" in m:
                lines.append(f"| {m['name']} | {m.get('offset')} | {m.get('size')} | {decl} | {m['disposition']} | | | |")
                for c in m["children"]:
                    emit(c)
                return
            lines.append(f"| {m['name']} | {m.get('offset')} | {m.get('size')} | {decl} | {m['disposition']} | "
                         f"{m.get('reads_runtime_count', '')} | {m.get('writes_validator_load_count', '')} | "
                         f"{m.get('writes_runtime_count', '')} |")
        for m in r["live_members"]:
            emit(m)
        lines.append("")
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    args = ap.parse_args(argv)
    payload, errors = build()
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    text = json.dumps(payload, indent=2, sort_keys=False) + "\n"
    md = write_markdown(payload)
    if args.write:
        (ROOT / OUT_JSON).write_text(text)
        (ROOT / OUT_MD).write_text(md)
        print(f"wrote {OUT_JSON} and {OUT_MD}: {payload['summary']}")
        return 0
    for rel, expected in ((OUT_JSON, text), (OUT_MD, md)):
        path = ROOT / rel
        if not path.exists() or path.read_text() != expected:
            print(f"{rel} is stale or missing; run with --write", file=sys.stderr)
            return 1
    print(f"ok: {payload['summary']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
