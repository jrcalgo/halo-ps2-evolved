#!/usr/bin/env python3
"""Regenerate and check the C4 DWARF-range dispositions.

The C4 member ledger (tools/audit_c4_member_ledger.py) carries rows for BSP
structure byte ranges that the schema does not cover and that DWARF/compiler
layout names as live CE members (inventory_classification "unclassified").
This tool resolves each such range to one of

  runtime-normalized  runtime-only field reset/filled at load, with journal evidence
  preserved-opaque    declared padding/unused/reserved, or no CE access at all
  consumed            persisted data field with a CE consumer (needs member-exact fixture)
  schema-gap          persisted/pointer-shaped field the schema omits and needs an addition
  blocked             with the exact reason

Nothing is hand-listed as evidence without being re-derived: declaration lines
come from the compiler-selected declaration (range layout JSONs), access sites
are regenerated by grepping CE source with receiver-aware patterns, and every
citation is a (path, needle) pair resolved to a line number at run time.  A
declared member disposition that the regenerated accesses contradict fails.

Usage:
  python3 tools/audit_c4_range_dispositions.py          # check committed outputs
  python3 tools/audit_c4_range_dispositions.py --write  # regenerate JSON and markdown
"""
