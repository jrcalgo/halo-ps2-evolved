#!/usr/bin/env python3
"""Keep the EE physical layout constant derived from the budget manifest."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BUDGET = ROOT / "config/memory-budget.json"
HEADER = ROOT / "src/stream/hcu_memory_budget_generated.h"


def render() -> str:
    budget = json.loads(BUDGET.read_text())
    regions = {row["name"]: row["bytes"] for row in budget["regions"]}
    assert sum(regions.values()) == budget["total_bytes"] == 32 * 1024 * 1024
    assert sum(v for k, v in regions.items() if k != "uncommitted_reserve") == budget["committed_bytes"]
    assert regions["uncommitted_reserve"] == budget["reserve_bytes"]
    reserve_start = 0x100000 + regions["elf_static"] + 26738688
    assert reserve_start == 0x01cf0000
    return ("/* Generated by tools/hcu_memory_budget_header.py from config/memory-budget.json. */\n"
            "#ifndef HCU_MEMORY_BUDGET_GENERATED_H\n#define HCU_MEMORY_BUDGET_GENERATED_H\n"
            f"#define HCU_ELF_STATIC_BYTES {regions['elf_static']}u\n"
            "#endif\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not HEADER.exists() or HEADER.read_text() != expected:
            parser.error("generated memory header is stale")
    else:
        HEADER.write_text(expected)
