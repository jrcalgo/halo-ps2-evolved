                        if x.get('sha256') == binding['sha256'] and not (x.get('path') or x.get('local_path')):
                            x['local_path'] = binding['path']
                            x['local_sha256'] = binding['sha256']
                            x['identity_resolution'] = 'verified target binding artifact'
