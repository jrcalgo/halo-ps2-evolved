                    unresolved.append({'category':cat,'label':x.get('reported_label'),'sha256':x.get('sha256'),'reason':'hash lacks local path, exact source-map key, or matching adjacent build output','report_adjacent_build_paths':sorted(str(p.relative_to(ROOT)) for p in mentioned),'adjacent_build_file_count':len(adjacent_files)})
