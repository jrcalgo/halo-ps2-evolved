                declared_path=x.get('local_path')
                raw_path=x.get('path')
                # Some upstream manifests use a `path` field as a human label
                # (e.g. "PCSX2 BIOS"), not as a filesystem path. Only interpret
                # it as one when it has path syntax; keep its digest for binding.
                is_path = bool(raw_path and (Path(raw_path).is_absolute() or '/' in raw_path or '\\' in raw_path or Path(raw_path).suffix))
                path=declared_path or (raw_path if is_path else None)
                expected=x.get('local_sha256') or x.get('sha256')
                if path:
                    p=ROOT/path
                    if p.is_file():
                        checked+=1; actual=sha(p)
                        if actual==expected: bound+=1
                        else: stale.append({'path':path,'declared_sha256':expected,'actual_sha256':actual,'category':cat})
                    else: unresolved.append({'category':cat,'label':x.get('reported_label'),'reason':'declared local path absent','path':path})
                elif cat=='fixture_hashes' and expected in synthetic_by_hash and r.get('subcheck')=='synthetic-empty-retail-bsp-fields':
                    syn=synthetic_by_hash[expected]; bound+=1; candidates.append({'path':syn['path'],'sha256':expected,'image_bytes':syn['image_bytes'],'schema_elf_sha256':syn['schema_elf_sha256'],'basis':syn['basis']})
                elif cat=='fixture_hashes' and x.get('map') in source_map:
                    m=source_map[x['map']]
                    if m['sha256']==x.get('sha256'):
                        bound+=1; candidates.append({'map':x['map'],'path':m['path'],'sha256':m['sha256'],'bytes':m['bytes'],'basis':'ledger source_maps exact filename+hash'})
                    else: unresolved.append({'category':cat,'map':x.get('map'),'reason':'map hash differs from source_maps'})
                elif expected in source_map_by_hash:
                    m=source_map_by_hash[expected]
                    bound+=1; candidates.append({'map':m['map'],'path':m['path'],'sha256':m['sha256'],'bytes':m['bytes'],'basis':'ledger source_maps exact digest; report pin label is not used to infer artifact type'})
                elif expected in raw_bsp_by_hash:
                    derived=raw_bsp_by_hash[expected]
                    bound+=1; candidates.append(derived)
