            # the local-player binding manifest pins the exact availability
            # report bytes and those bytes record an empty exact-match search.
            # Recheck every expected current source path; this never treats a
            # replacement source or rebuilt executable as a historical match.
            availability_link = local_player.get('historical_pin_availability_report') or {}
            availability_link_path = availability_link.get('path')
