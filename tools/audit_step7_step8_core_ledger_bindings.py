                if not bound_path.is_absolute():
                    bound_path = ROOT / bound_path
                actual = sha(bound_path) if bound_path.is_file() else None
                if actual != binding.get('sha256'):
                    stale.append({'path':binding['path'],'declared_sha256':binding.get('sha256'),'actual_sha256':actual,'category':'local_player_identity_binding'})
