#!/usr/bin/env python3
"""Generate the C5 local-setup qualified rows from the measured C2 evidence.

Inputs (read only):
  src/stream/hcu_memory_profile.c           partition table hcu_partition_table_v2
  docs/reports/m2-c2-profile-guarded-fit-2026-10-24.json   per-profile guest fit
  docs/reports/m2-c2-profile-matrix-2026-10-24.json        per-row matrix pass

Outputs:
  src/stream/hcu_local_setup_rows.inc                 generated row table
  docs/reports/m4-c5-local-setup-rows-2026-10-26.json  evidence and per-row reasons

A row is qualified for a local setup only when population evidence exists. The
C2 fit is a load-and-release fit (production CE load, then release); the
4-player and bot workload runs are diagnostics, not profile fits, and no run
exercised bots. So every row is emitted with qualified=0, zero humans, zero
bots and an empty difficulty mask. Difficulty was never measured. The
validator therefore refuses every setup until real population and difficulty
evidence is recorded here.
"""
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PARTITION_C = ROOT / "src/stream/hcu_memory_profile.c"
FIT_JSON = ROOT / "docs/reports/m2-c2-profile-guarded-fit-2026-10-24.json"
MATRIX_JSON = ROOT / "docs/reports/m2-c2-profile-matrix-2026-10-24.json"
INC_OUT = ROOT / "src/stream/hcu_local_setup_rows.inc"
REPORT_OUT = ROOT / "docs/reports/m4-c5-local-setup-rows-2026-10-26.json"

PROFILE_RE = re.compile(r'\{\s*"([a-z0-9_]+)",\s*\{')
GAMEPLAY_ROLES = ("marine_shotgun_4p4bot", "mounted_gunner_4p4bot")


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def partition_names(source: str) -> list:
    start = source.index("hcu_partition_table_v2[] = {")
    end = source.index("};", start)
    return PROFILE_RE.findall(source[start:end])


def main() -> int:
    names = partition_names(PARTITION_C.read_text())
    fit = json.loads(FIT_JSON.read_text())
    matrix = json.loads(MATRIX_JSON.read_text())
    fit_by_name = {p["profile"]: p for p in fit["profiles"]}
    matrix_by_name = {r["row"]: r for r in matrix["rows"]}

    profiles = []
    for name in names:
        reasons = []
        fit_row = fit_by_name.get(name)
        mrow = matrix_by_name.get(name)
        if fit_row is None:
            reasons.append("no guarded fit record for this profile")
        else:
            if fit_row.get("profile_specific_guest_fit") != "measured_pass":
                reasons.append("guest fit not measured_pass")
            if not fit_row.get("hcp_package_sha256_matches_manifest"):
                reasons.append("package sha does not match manifest")
        if mrow is None:
            reasons.append("no profile matrix row")
        elif mrow.get("pass") is not True:
            reasons.append("profile matrix row did not pass")
        if name == "ui":
            reasons.append("menu package, not a gameplay setup target")
        if name == "bots_sidewinder":
            reasons.append("static package-derived candidate, no measured fit")
        load_qualified = not reasons
        profiles.append({
            "profile": name,
            "map": name.split("_")[0] if name not in ("ui", "bots_sidewinder") else name,
            "role": next((r for r in GAMEPLAY_ROLES if name.endswith(r)), None),
            "load_fit_measured": load_qualified,
            "reasons": reasons,
        })

    # Population and difficulty evidence: none recorded in the fit or matrix.
    population_gaps = [
        "no completed 4-player or bot gameplay workload is a profile fit (diagnostic only)",
        "bots were never exercised (workload runs record bots=not-exercised)",
        "no difficulty dimension was measured",
    ]

    maps = []
    for name in ("beavercreek", "bloodgulch", "boardingaction", "carousel", "chillout",
                 "damnation", "hangemhigh", "longest", "prisoner", "putput", "ratrace",
                 "sidewinder", "wizard"):
        roles = {p["role"]: p for p in profiles if p["map"] == name and p["role"]}
        load_ok = all(roles.get(r, {}).get("load_fit_measured") for r in GAMEPLAY_ROLES)
        reasons = list(population_gaps)
        if not load_ok:
            reasons.insert(0, "a gameplay role lacks a measured load fit")
        maps.append({"map": name, "mode": "HCU_LOCAL_MODE_STOCK_COOP",
                     "load_fit_measured": load_ok, "qualified": False,
                     "difficulty_mask": 0, "max_humans": 0, "max_bots": 0,
                     "reasons": reasons})

    rows_inc = [
        "/* Generated by tools/c5_local_setup_rows.py from the C2 evidence.",
        " * Do not edit by hand. Every row is qualified=0: see the report at",
        " * docs/reports/m4-c5-local-setup-rows-2026-10-26.json for the gaps. */",
        "#define HCU_LOCAL_GENERATED_ROW_COUNT %d" % len(maps),
        "static const hcu_local_qualified_row hcu_local_generated_rows[HCU_LOCAL_GENERATED_ROW_COUNT] = {",
    ]
    for m in maps:
        rows_inc.append('\t{ "%s", %s, 0x%xu, %du, %du }, /* qualified=0 load_fit=%d */' % (
            m["map"], m["mode"], m["difficulty_mask"], m["max_humans"], m["max_bots"],
            1 if m["load_fit_measured"] else 0))
    rows_inc.append("};")
    INC_OUT.write_text("\n".join(rows_inc) + "\n")

    report = {
        "format": "hcu-c5-local-setup-rows-v1",
        "date": "2026-10-26",
        "generator": "tools/c5_local_setup_rows.py",
        "inputs": {
            str(PARTITION_C.relative_to(ROOT)): sha256(PARTITION_C),
            str(FIT_JSON.relative_to(ROOT)): sha256(FIT_JSON),
            str(MATRIX_JSON.relative_to(ROOT)): sha256(MATRIX_JSON),
        },
        "output": {str(INC_OUT.relative_to(ROOT)): sha256(INC_OUT)},
        "qualified_row_count": 0,
        "summary": ("No row is qualified for a local setup. The C2 evidence is a load-and-release fit. "
                    "It has no population or difficulty dimension, so humans, bots and difficulty stay at zero."),
        "partition_profiles": profiles,
        "setup_rows": maps,
        "gaps": population_gaps,
    }
    REPORT_OUT.write_text(json.dumps(report, indent=2) + "\n")
    print("wrote %s and %s; qualified rows: 0 of %d" % (
        INC_OUT.name, REPORT_OUT.name, len(maps)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
